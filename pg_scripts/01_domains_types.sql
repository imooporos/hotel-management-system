-- ============================================================================
--  01_domains_types.sql
--  Пользовательские домены и перечислимые типы предметной области.
--  Запускается первым в цепочке скриптов воспроизведения БД.
-- ============================================================================

\echo '>>> applying 01_domains_types.sql'

-- ---------------------------------------------------------------------------
--  Расширения
-- ---------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS pgcrypto;     -- gen_random_uuid(), crypt()
CREATE EXTENSION IF NOT EXISTS btree_gist;   -- EXCLUDE с GiST по диапазонам

-- ---------------------------------------------------------------------------
--  Чистка предыдущих определений (для идемпотентности скрипта)
-- ---------------------------------------------------------------------------
DROP DOMAIN IF EXISTS email_domain    CASCADE;
DROP DOMAIN IF EXISTS phone_domain    CASCADE;
DROP DOMAIN IF EXISTS positive_money  CASCADE;
DROP TYPE   IF EXISTS room_status     CASCADE;
DROP TYPE   IF EXISTS booking_status  CASCADE;
DROP TYPE   IF EXISTS payment_method  CASCADE;
DROP TYPE   IF EXISTS audit_action    CASCADE;

-- ---------------------------------------------------------------------------
--  Домен: email
--  Принимает строки вида local@host.tld, проверяет регулярным выражением.
-- ---------------------------------------------------------------------------
CREATE DOMAIN email_domain AS varchar(255)
    CHECK (
        VALUE ~* '^[A-Z0-9._%+\-]+@[A-Z0-9.\-]+\.[A-Z]{2,}$'
    );

COMMENT ON DOMAIN email_domain IS
    'Email-адрес. Регистронезависимая валидация формата local@host.tld.';

-- ---------------------------------------------------------------------------
--  Домен: телефон
--  Принимает международный формат +7XXXXXXXXXX (10–15 цифр после плюса)
--  либо локальный формат из 10–11 цифр. Допускаются скобки/тире/пробелы.
-- ---------------------------------------------------------------------------
CREATE DOMAIN phone_domain AS varchar(32)
    CHECK (
        regexp_replace(VALUE, '[\s\-\(\)]', '', 'g')
        SIMILAR TO '\+?[0-9]{10,15}'
    );

COMMENT ON DOMAIN phone_domain IS
    'Номер телефона. Допустимы +, пробелы, скобки, тире; цифр 10–15.';

-- ---------------------------------------------------------------------------
--  Домен: положительная денежная сумма (NUMERIC(12,2))
-- ---------------------------------------------------------------------------
CREATE DOMAIN positive_money AS numeric(12, 2)
    CHECK (VALUE >= 0);

COMMENT ON DOMAIN positive_money IS
    'Денежная сумма с двумя знаками после запятой. Не может быть отрицательной.';

-- ---------------------------------------------------------------------------
--  ENUM: статус номера
-- ---------------------------------------------------------------------------
CREATE TYPE room_status AS ENUM (
    'available',     -- свободен
    'occupied',      -- заселён
    'reserved',      -- забронирован
    'maintenance',   -- на обслуживании / ремонте
    'cleaning'       -- уборка
);

COMMENT ON TYPE room_status IS
    'Жизненный цикл состояния гостиничного номера.';

-- ---------------------------------------------------------------------------
--  ENUM: статус бронирования
-- ---------------------------------------------------------------------------
CREATE TYPE booking_status AS ENUM (
    'pending',       -- ожидает подтверждения
    'confirmed',     -- подтверждено менеджером
    'checked_in',    -- гость заселён
    'checked_out',   -- гость выехал
    'cancelled'      -- отменено
);

COMMENT ON TYPE booking_status IS
    'Жизненный цикл бронирования. Допустимые переходы заданы в sp_update_booking_status.';

-- ---------------------------------------------------------------------------
--  ENUM: метод оплаты
-- ---------------------------------------------------------------------------
CREATE TYPE payment_method AS ENUM (
    'cash',
    'card',
    'transfer',
    'online'
);

COMMENT ON TYPE payment_method IS 'Способ оплаты бронирования.';

-- ---------------------------------------------------------------------------
--  ENUM: действие аудита
-- ---------------------------------------------------------------------------
CREATE TYPE audit_action AS ENUM (
    'INSERT',
    'UPDATE',
    'DELETE'
);

COMMENT ON TYPE audit_action IS 'Тип записи в audit_log.';

\echo '<<< 01_domains_types.sql ok'
